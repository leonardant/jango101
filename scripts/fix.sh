#!/usr/bin/env bash

set -euo pipefail


# ============================================================
# Locate repository root
# ============================================================

PROJECT_ROOT="$(git rev-parse --show-toplevel)"

cd "$PROJECT_ROOT"


# ============================================================
# Helper
# ============================================================

section() {
    echo
    echo "============================================================"
    echo "$1"
    echo "============================================================"
}


# ============================================================
# Ruff automatic fixes
# ============================================================

section "Applying Ruff fixes"

uv run ruff check . --fix


# ============================================================
# Ruff formatting
# ============================================================

section "Formatting code with Ruff"

uv run ruff format .


# ============================================================
# Final validation
# ============================================================

section "Checking Ruff"

uv run ruff check .


section "Checking formatting"

uv run ruff format --check .


echo
echo "============================================================"
echo "FIX AND FORMAT COMPLETE"
echo "============================================================"